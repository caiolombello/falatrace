var compiled = PATTERNS.map(function(entry) { return { pattern: new RegExp(entry[0]), replacement: entry[1], groups: entry[2] || [] } });

function applyPattern(rule, text) {
    var match = rule.pattern.exec(text);
    if (match === null) return null;
    return rule.replacement.replace(/\$(\d)/g, function(_, digit) {
        var index = Number(digit), value = match[index] === undefined ? "" : match[index];
        return rule.groups.indexOf(index) >= 0 ? translate(value) : value;
    });
}

function exact(text) {
    if (Object.prototype.hasOwnProperty.call(EN, text)) return EN[text];
    for (var index = 0; index < compiled.length; index++) {
        var value = applyPattern(compiled[index], text);
        if (value !== null) return value;
    }
    return null;
}

// Splits after . ! ? or … followed by a capital letter or a file name such as worker.env.
// The Qt JavaScript engine has no lookbehind, so boundaries are found with a lookahead
// and sliced by hand.
function sentences(text) {
    var result = [], start = 0, match, boundary = /[.!?…]\s+(?=[A-ZÀ-Ý"(]|[a-z]+\.(?:env|json)\b)/g;
    while ((match = boundary.exec(text)) !== null) {
        result.push(text.slice(start, match.index + 1));
        start = match.index + match[0].length;
    }
    result.push(text.slice(start));
    return result;
}

// Bridge messages are often several known sentences glued together, so an unknown text is
// translated sentence by sentence; unknown sentences stay as they are.
function translate(text) {
    if (typeof text !== "string" || text === "") return text;
    var whole = exact(text);
    if (whole !== null) return whole;
    var parts = sentences(text);
    if (parts.length < 2) return text;
    var changed = false;
    var translated = parts.map(function(part) {
        var value = exact(part);
        if (value === null) return part;
        changed = true;
        return value;
    });
    return changed ? translated.join(" ") : text;
}
